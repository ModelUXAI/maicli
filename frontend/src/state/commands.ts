/** Filter untuk palette: cocokkan nama atau alias. */
export function filterCommands(query: string): KnownCommand[] {
  const q = query.trim().toLowerCase();
  if (q.length === 0) return KNOWN_COMMANDS;
  return KNOWN_COMMANDS.filter(
    (cmd) =>
      cmd.name.startsWith(q) || cmd.aliases.some((alias) => alias.startsWith(q)),
  );
}
